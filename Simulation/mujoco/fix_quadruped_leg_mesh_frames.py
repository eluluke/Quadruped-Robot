from __future__ import annotations

import math
import struct
from collections import defaultdict, deque
from pathlib import Path

import numpy as np


SCRIPT_DIR = Path(__file__).resolve().parent
if (SCRIPT_DIR.parent / "Quadruped_Rear_Left_URDF").exists():
    SIMULATION_DIR = SCRIPT_DIR.parent
else:
    SIMULATION_DIR = SCRIPT_DIR.parent / "Simulation"
SOURCE_MESH_DIR = SIMULATION_DIR / "Quadruped_Rear_Left_URDF" / "meshes"
OUTPUT_MESH_DIR = SIMULATION_DIR / "mujoco" / "generated_meshes"


def rpy_matrix(roll: float, pitch: float, yaw: float) -> np.ndarray:
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)

    rx = np.array([[1, 0, 0], [0, cr, -sr], [0, sr, cr]])
    ry = np.array([[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]])
    rz = np.array([[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]])
    return rz @ ry @ rx


def transform_matrix(xyz: tuple[float, float, float], rpy: tuple[float, float, float]) -> np.ndarray:
    out = np.eye(4)
    out[:3, :3] = rpy_matrix(*rpy)
    out[:3, 3] = np.array(xyz)
    return out


def vertex_key(point: np.ndarray) -> tuple[float, float, float]:
    return tuple(round(float(value), 5) for value in point)


def bbox_volume(points: list[np.ndarray]) -> float:
    lo = np.min(points, axis=0)
    hi = np.max(points, axis=0)
    return float(np.prod(np.maximum(hi - lo, 0.0)))


def read_triangles(src: Path, link_from_world: np.ndarray) -> list[tuple[np.ndarray, list[np.ndarray]]]:
    data = src.read_bytes()
    tri_count = struct.unpack_from("<I", data, 80)[0]
    rot = link_from_world[:3, :3]
    trans = link_from_world[:3, 3]
    triangles: list[tuple[np.ndarray, list[np.ndarray]]] = []

    offset = 84
    for _ in range(tri_count):
        normal = np.array(struct.unpack_from("<fff", data, offset))
        normal = rot @ normal
        norm = np.linalg.norm(normal)
        if norm > 0:
            normal = normal / norm
        offset += 12

        points = []
        for _ in range(3):
            point = np.array(struct.unpack_from("<fff", data, offset))
            points.append(rot @ point + trans)
            offset += 12
        triangles.append((normal, points))
        offset += 2

    return triangles


def connected_components(triangles: list[tuple[np.ndarray, list[np.ndarray]]]) -> list[list[int]]:
    vertex_to_triangles: defaultdict[tuple[float, float, float], list[int]] = defaultdict(list)
    for index, (_, points) in enumerate(triangles):
        for point in points:
            vertex_to_triangles[vertex_key(point)].append(index)

    seen = [False] * len(triangles)
    components: list[list[int]] = []
    for start in range(len(triangles)):
        if seen[start]:
            continue
        queue: deque[int] = deque([start])
        seen[start] = True
        component: list[int] = []
        while queue:
            index = queue.popleft()
            component.append(index)
            for point in triangles[index][1]:
                for other in vertex_to_triangles[vertex_key(point)]:
                    if not seen[other]:
                        seen[other] = True
                        queue.append(other)
        components.append(component)
    return components


def largest_volume_component(triangles: list[tuple[np.ndarray, list[np.ndarray]]]) -> set[int]:
    best: list[int] = []
    best_volume = -1.0
    for component in connected_components(triangles):
        points = [point for index in component for point in triangles[index][1]]
        volume = bbox_volume(points)
        if volume > best_volume:
            best = component
            best_volume = volume
    return set(best)


def write_binary_stl(dst: Path, triangles: list[tuple[np.ndarray, list[np.ndarray]]]) -> None:
    out = bytearray(84 + len(triangles) * 50)
    out[:80] = b"generated by fix_quadruped_leg_mesh_frames.py".ljust(80, b" ")
    struct.pack_into("<I", out, 80, len(triangles))

    offset = 84
    for normal, points in triangles:
        struct.pack_into("<fff", out, offset, *normal)
        offset += 12
        for point in points:
            struct.pack_into("<fff", out, offset, *point)
            offset += 12
        struct.pack_into("<H", out, offset, 0)
        offset += 2

    dst.write_bytes(out)


def split_mesh(
    src: Path,
    moving_dst: Path,
    fixed_dst: Path | None,
    moving_frame_from_world: np.ndarray,
    fixed_frame_from_world: np.ndarray | None = None,
) -> None:
    moving_triangles = read_triangles(src, moving_frame_from_world)
    moving_component = largest_volume_component(moving_triangles)
    write_binary_stl(
        moving_dst,
        [triangle for index, triangle in enumerate(moving_triangles) if index in moving_component],
    )

    if fixed_dst is None or fixed_frame_from_world is None:
        return

    fixed_triangles = read_triangles(src, fixed_frame_from_world)
    write_binary_stl(
        fixed_dst,
        [triangle for index, triangle in enumerate(fixed_triangles) if index not in moving_component],
    )


def write_whole_mesh(src: Path, dst: Path, frame_from_world: np.ndarray) -> None:
    write_binary_stl(dst, read_triangles(src, frame_from_world))


def main() -> None:
    OUTPUT_MESH_DIR.mkdir(exist_ok=True)

    world_from_leg = np.eye(4)
    world_from_hip = world_from_leg @ transform_matrix(
        (-0.10814, 0, 0),
        (1.5708, 0.96031, -1.5708),
    )
    world_from_thigh = world_from_hip @ transform_matrix(
        (-0.12389, 0.086678, -0.10814),
        (-1.5708, 0.094043, 0.96031),
    )
    world_from_shank = world_from_thigh @ transform_matrix(
        (0, 0, -0.1508),
        (-3.1416, 0, -2.712),
    )

    leg_from_world = np.linalg.inv(world_from_leg)
    hip_from_world = np.linalg.inv(world_from_hip)
    thigh_from_world = np.linalg.inv(world_from_thigh)
    shank_from_world = np.linalg.inv(world_from_shank)

    write_whole_mesh(SOURCE_MESH_DIR / "Leg_FR.STL", OUTPUT_MESH_DIR / "Leg_FR.STL", leg_from_world)
    split_mesh(
        SOURCE_MESH_DIR / "Hip_Link.STL",
        OUTPUT_MESH_DIR / "Hip_Link.STL",
        None,
        hip_from_world,
    )
    split_mesh(
        SOURCE_MESH_DIR / "Thigh_Link.STL",
        OUTPUT_MESH_DIR / "Thigh_Link.STL",
        OUTPUT_MESH_DIR / "Thigh_Actuator.STL",
        thigh_from_world,
        hip_from_world,
    )
    split_mesh(
        SOURCE_MESH_DIR / "Shank_Link.STL",
        OUTPUT_MESH_DIR / "Shank_Link.STL",
        OUTPUT_MESH_DIR / "Shank_Actuator.STL",
        shank_from_world,
        thigh_from_world,
    )

    for path in sorted(OUTPUT_MESH_DIR.glob("*_Link.STL")) + [OUTPUT_MESH_DIR / "Leg_FR.STL", OUTPUT_MESH_DIR / "Thigh_Actuator.STL", OUTPUT_MESH_DIR / "Shank_Actuator.STL"]:
        if path.exists():
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
